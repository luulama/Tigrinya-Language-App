"""Package sourced lip components. Never infer syllables, approval or audio timings."""
from pathlib import Path
import hashlib
import json
import re
import subprocess
from xml.etree import ElementTree

root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'shared/content-review/articulation.json').read_text())
inventory = json.loads((root / 'shared/content-review/fidal-writing.json').read_text())
cards = {p['character']: (f['family'], p['order']) for f in inventory['families'] for p in f['forms']}
assert data['schemaVersion'] == 1 and data['language'] == 'ti'
assert len({p['id'] for p in data['profiles']}) == len(data['profiles'])
assert len({b['character'] for b in data['bindings']}) == len(data['bindings'])
sources = {s['id'] for s in data['sources']}
profiles = {p['id']: p for p in data['profiles']}
for p in profiles.values():
    body = {k: v for k, v in p.items() if k not in ['review', 'revision']}
    p['revision'] = hashlib.sha256(json.dumps(body, sort_keys=True, ensure_ascii=False).encode() + (root/'shared/mascot/neri.js').read_bytes()).hexdigest()[:20]
    assert p['scope'] == 'consonant-component' and p['evidenceStatus'] == 'source-supported'
    assert len(p['sourceIds']) >= 2 and set(p['sourceIds']) <= sources
    assert len(p['steps']) == 3
    for s in p['steps']:
        assert s['label'] and s['cue']
        assert set(s['pose']) == {'open', 'contact', 'nasal'}
        assert all(isinstance(v, (int, float)) and 0 <= v <= 1 for v in s['pose'].values())
for b in data['bindings']:
    assert cards[b['character']] == (b['family'], b['order'])
    assert b['order'] in [1, 2, 3, 4, 5, 7] and b['profile'] in profiles
for a in data['alignments']:
    assert a['status'] == 'approved' and a['scope'] == 'consonant-component'
    assert a['language'] == 'ti'
    assert a['speed'] in ['normal', 'slow'] and a['targetKind'] == 'syllabic-form'
    assert a['character'] in {b['character'] for b in data['bindings']}
    assert a['profile'] in profiles
    assert profiles[a['profile']]['review']['status'] == 'approved', 'The illustration/guide needs its own qualified review before synchronized use'
    assert profiles[a['profile']]['review'].get('revision') == profiles[a['profile']]['revision'], 'The guide drawing or prompts changed since review'
    for key in ['reviewer', 'reviewedAt', 'variety', 'sourceLocator', 'rights']:
        assert isinstance(a[key], str) and a[key].strip()
    assert re.fullmatch(r'\d{4}-\d{2}-\d{2}', a['reviewedAt'])
    assert a['sourceUrl'].startswith('https://')
    asset = a['audioPath'].removeprefix('../shared/')
    assert re.fullmatch(r'assets/[A-Za-z0-9_./-]+\.(mp3|wav|ogg|m4a)', asset) and '..' not in asset
    assert hashlib.sha256((root/'shared'/asset).read_bytes()).hexdigest() == a['sha256'], 'Alignment must match the reviewed recording bytes'
    assert 0 < a['durationMs'] and len(a['frames']) >= 3
    for i, f in enumerate(a['frames']):
        assert 0 <= f['atMs'] <= a['durationMs'] and (not i or f['atMs'] > a['frames'][i-1]['atMs'])
        assert f['stage'] in [0,1,2] and all(0 <= f['pose'][k] <= 1 for k in ['open','contact','nasal'])
(root/'shared/mascot/articulation-data.js').write_text('// Generated by scripts/build_mascot.py. Source-supported draft components; no native approval implied.\n' + 'globalThis.MascotArticulationData = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n')
print(f'Built Neri lip guides: {len(profiles)} sourced consonant components, {len(data["bindings"])} exact form bindings, {len(data["alignments"])} reviewed audio timelines.')
subprocess.run(['node', str(root/'scripts/export_mascot.cjs')], cwd=root, check=True)
for asset in (root/'shared/mascot/assets').glob('*.svg'):
    assert ElementTree.parse(asset).getroot().tag == '{http://www.w3.org/2000/svg}svg', f'Invalid standalone SVG: {asset.name}'
print('Validated all 18 standalone bear and human-guide SVGs as XML, including their mouth groups.')
