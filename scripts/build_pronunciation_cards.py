"""Build cards from the existing Fidäl inventory and explicit pronunciation reviews.

Never download, synthesise or approve pronunciation. See PRONUNCIATION_CARDS.md.
"""
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
inventory = json.loads((root / 'shared/content-review/fidal-writing.json').read_text())
reviews = json.loads((root / 'shared/content-review/pronunciation-cards.json').read_text())
assert reviews['schemaVersion'] == 1 and reviews['language'] == 'ti'
targets = {row['character']: row for row in reviews['targets']}
assert len(targets) == len(reviews['targets']), 'Duplicate pronunciation target'
cards = []
known = set()
for family in inventory['families']:
    for profile in family['forms']:
        char = profile['character']
        known.add(char)
        target = targets.get(char)
        if target:
            assert target.get('kind') in ['syllabic-form', 'contextual-word']
            if profile['order'] == 6:
                assert target['kind'] == 'contextual-word', 'Sixth order needs a reviewed word context'
            if target['kind'] == 'contextual-word':
                assert any(c['word'] == target.get('text') and c['status'] == 'approved'
                           for c in profile['contexts']), 'Use an approved existing word context'
            if target.get('status') == 'approved':
                for speed in ['normal', 'slow']:
                    asset = profile['audio'].get(speed)
                    assert isinstance(asset, str) and re.fullmatch(r'(?:\.\./shared/)?assets/[A-Za-z0-9_./-]+\.(?:mp3|wav|ogg|m4a)', asset)
                    local = asset.removeprefix('../shared/')
                    assert '..' not in local and (root / 'shared' / local).is_file(), 'Reviewed audio file is missing'
        cards.append({
            'character': char, 'family': family['family'], 'order': profile['order'],
            'kind': family['kind'], 'unicode': profile['unicode'],
            'structureSources': profile['structureSources'],
            'target': target, 'audio': profile['audio'],
        })
assert set(targets) <= known, 'Unknown Fidäl target'
data = {'schemaVersion': 1, 'language': 'ti', 'direction': 'ltr',
        'sources': inventory['sources'], 'cards': cards}
out = '// Generated by scripts/build_pronunciation_cards.py; review records are the source.\n'
out += 'globalThis.PronunciationCardContent = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
(root / 'unit-01-fidel-foundations/pronunciation-content.js').write_text(out)
print(f'Built {len(cards)} Fidäl cards; {len(targets)} explicit pronunciation targets. No approval invented.')
