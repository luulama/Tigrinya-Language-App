"""Build the offline Fidäl content module from review records, without fetching."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
data = json.loads((root / 'shared/content-review/fidal-writing.json').read_text(encoding='utf-8'))
module = '// Generated by scripts/build_fidal.py; edit the review JSON.\n'
module += 'globalThis.FidalContent = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
(root / 'shared/fidal-content.js').write_text(module, encoding='utf-8')
print('Built shared/fidal-content.js')
