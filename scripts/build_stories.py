"""Package original story drafts and existing review decisions; never approve content."""
from pathlib import Path
import json
import hashlib
import unicodedata
import re
import subprocess
import sys

root = Path(__file__).resolve().parents[1]
source = json.loads((root / 'stories/content/collection.json').read_text())
reviews = json.loads((root / 'stories/content/review.json').read_text())
subprocess.run([sys.executable, str(root / 'scripts/build_story_art.py')], check=True)
records = {r['id']: r for r in reviews['stories']}
required_checks = {'meaning-and-story-coherence', 'natural-tigrinya', 'spelling-and-punctuation', 'gender-and-verb-agreement', 'variety-and-register', 'age-and-bedtime-suitability', 'fiction-and-cultural-care', 'illustration-alignment', 'reading-demand'}
assert source['language'] == 'ti' and source['direction'] == 'ltr'
assert len(source['stories']) == 20 and len(records) == 20
stories = []
for order, s in enumerate(source['stories'], 1):
    assert re.fullmatch(r'[a-z]+(?:-[a-z]+)*', s['id'])
    assert len(s['paragraphs']) >= 8 and all(len(p.split()) >= 8 for p in s['paragraphs'])
    assert all(unicodedata.normalize('NFC', p) == p for p in [s['title'], *s['paragraphs']])
    assert not re.search(r'[A-Za-z]', ''.join([s['title'], *s['paragraphs']]))
    art = root / 'stories/assets' / (s['id'] + '.svg')
    revision = hashlib.sha256(json.dumps(s, ensure_ascii=False, sort_keys=True).encode() + art.read_bytes()).hexdigest()[:20]
    r = records[s['id']]
    assert set(r['checks']) == required_checks, 'Review checklist must remain complete'
    approved = (r['status'] == 'approved' and r.get('revision') == revision
                and r.get('reviewer') and r.get('reviewedAt') and r.get('variety')
                and all(v == 'approved' for v in r['checks'].values()))
    stories.append({
        'id': s['id'], 'title': s['title'], 'editorialTitle': s['editorialTitle'],
        'order': order, 'part': s['part'], 'theme': s['theme'],
        'revision': revision, 'reviewStatus': 'approved' if approved else 'awaiting-fluent-tigrinya-review',
        'audio': None, 'approvedForLearnerRelease': False,
        'paragraphs': [{'id': f'p{n}', 'text': p, 'audio': None} for n,p in enumerate(s['paragraphs'], 1)],
        'illustrations': [{'src': 'assets/' + s['id'] + '.svg', 'alt': s['alt'], 'afterParagraph': 2}],
    })
data = {'schemaVersion': 1, 'language': 'ti', 'direction': 'ltr',
        'authorship': source['authorship'], 'stories': stories}
output = json.dumps(data, ensure_ascii=False, indent=2)
(root / 'stories/catalog.json').write_text(output + '\n')
(root / 'stories/data.js').write_text('// Generated by scripts/build_stories.py; edit stories/content/.\n' + 'globalThis.StoryLibraryContent = ' + output + ';\n')
print(f'Built {len(stories)} complete original story drafts, {sum(len(s["paragraphs"]) for s in stories)} paragraphs and 20 local illustrations.')
